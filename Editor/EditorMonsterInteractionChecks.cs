using System.Numerics;
using Raylib_cs;
using static Raylib_cs.Raylib;

sealed partial class EditorApp
{
    public void RunMonsterInteractionChecks()
    {
        SetWindowSize(1440, 900); play = null; document.New(16, 16); tool = EditTool.Select; selectedId = null;
        focus = Vector3.Zero; camera.Snap(focus); TestFrame();
        ClickHeader("Monster"); Verify(tool == EditTool.Monster, "Monster toolbar button");
        var point = GetWorldToScreenEx(new(4, 0, 0), camera.View, (int)viewport.Width, (int)viewport.Height) + new Vector2(viewport.X, viewport.Y);
        Click((int)point.X, (int)point.Y);
        Verify(document.Map.Monsters.Count == 1 && Selection is MonsterData && tool == EditTool.Monster, "placing a monster keeps the Monster tab");
        Click(GetScreenWidth() - Right + 125, 287);
        Verify(EditedMonster?.Id == Selection!.Id, "Monster tab opens the placed actor's stats");
        Press(KeyboardKey.Escape); Verify(monsterSettingsId == null && tool == EditTool.Monster, "closing Stats keeps the Monster tab");
        Click((int)point.X, (int)point.Y);
        Verify(document.Map.Monsters.Count == 2 && tool == EditTool.Monster, "next map click places another monster");
        ClickHeader("Undo"); Verify(document.Map.Monsters.Count == 1 && tool == EditTool.Monster, "undo repeated monster placement keeps the tab");
        ClickHeader("Select");
        var monster = document.Map.Monsters.Single(); string id = monster.Id;
        var center = renderer.GetSpriteQuad(camera.View, monster.Asset, document.Map.GroundPosition(monster), monster.Height).Center;
        point = GetWorldToScreenEx(center, camera.View, (int)viewport.Width, (int)viewport.Height) + new Vector2(viewport.X, viewport.Y);
        Click((int)point.X, (int)point.Y); Verify(selectedId == id, "monster ray picking");
        var oldPosition = monster.Position;
        Input(7, (int)point.X, (int)point.Y); Input(6, 0); TestFrame();
        Input(7, (int)point.X - 40, (int)point.Y + 20); TestFrame();
        Input(7, (int)point.X - 40, (int)point.Y + 20); Input(5, 0); TestFrame();
        Verify(monster.Position != oldPosition, "monster dragging");
        ClickHeader("Undo"); monster = document.Map.Monsters.Single(); Verify(monster.Position == oldPosition, "undo monster drag");
        int ix = GetScreenWidth() - Right + 18;
        Click(ix + 200, 316); Verify(Selection!.Height == 1.85f, "monster height inspector");
        ClickHeader("Undo"); monster = document.Map.Monsters.Single();
        Click(ix + 30, 437); Verify(textEdit != null, "monster Name button"); AppendEdit("Żmij"); Press(KeyboardKey.Enter);
        Verify(monster.Name == "Żmij", "monster Polish name applies");
        Click(ix + 106, 437); Verify(tool == EditTool.Monster, "monster Sprite opens character palette");
        string sprite = assets.Sprites.Keys.First(); ChangeActorCharacter(sprite, EditTool.Monster);
        Verify(monster.Asset == sprite && chosenMonsterCharacter == sprite, "monster sprite choice updates actor and next placement");
        Click(110, 156); Verify(monster.Asset == "" && chosenMonsterCharacter == null, "red placeholder clears the monster sprite");
        ClickHeader("Select"); Click(ix + 178, 437);
        Verify(EditedMonster?.Id == id, "Stats opens monster configuration");
        var box = MonsterSettingsBounds; int x = (int)box.X, y = (int)box.Y;
        Click(x + 224, y + 132); Verify(EditedMonster!.MaxHealth == 35, "HP stat control");
        Input(2, (int)KeyboardKey.LeftControl); Press(KeyboardKey.Z); Input(1, (int)KeyboardKey.LeftControl); TestFrame();
        Verify(EditedMonster!.MaxHealth == 30, "undo stats while configuration remains open");
        Input(2, (int)KeyboardKey.LeftControl); Press(KeyboardKey.Y); Input(1, (int)KeyboardKey.LeftControl); TestFrame();
        Verify(EditedMonster!.MaxHealth == 35, "redo stats refreshes the edited actor");
        Click(x + 514, y + 132); Verify(EditedMonster!.Damage == 11, "damage stat control");
        Click(x + 224, y + 206); Verify(EditedMonster!.MoveSpeed == 2.6f, "speed stat control");
        Click(x + 514, y + 206); Verify(EditedMonster!.DetectionRange == 7, "detection stat control");
        Click(x + 224, y + 280); Verify(EditedMonster!.AttackRange == 1.25f, "attack range stat control");
        Click(x + 330, y + 280); Verify(EditedMonster!.AttackCooldown == .9f, "attack cooldown stat control");
        TestFrame(); TestFrame(); WorldRenderer.Screenshot(Path.Combine(ProjectPaths.Root, "Editor", "obj", "monster-editor.png"));
        SetWindowSize(1120, 720); TestFrame(); TestFrame(); box = MonsterSettingsBounds;
        Verify(box.X >= 0 && box.Y >= 0 && box.X + box.Width <= GetScreenWidth() && box.Y + box.Height <= GetScreenHeight(), "monster settings fit the minimum window");
        Press(KeyboardKey.Escape); Verify(monsterSettingsId == null, "Escape closes monster configuration");
        ClickHeader("Monster"); Verify(tool == EditTool.Monster, "all nine tools remain accessible at minimum window size");
        Press(KeyboardKey.One); SetWindowSize(1440, 900); TestFrame(); TestFrame();
        Input(2, (int)KeyboardKey.LeftControl); Press(KeyboardKey.D); Input(1, (int)KeyboardKey.LeftControl); TestFrame();
        var copy = document.Map.Monsters.Last();
        Verify(document.Map.Monsters.Count == 2 && copy.Id != id && copy.MaxHealth == 35 && copy.Damage == 11 && copy.Name == "Żmij", "monster duplication retains stats");
        Press(KeyboardKey.Delete); Verify(document.Map.Monsters.Count == 1, "monster deletion");
        ClickHeader("Undo"); Verify(document.Map.Monsters.Count == 2, "undo monster deletion");
        ClickHeader("Redo"); Verify(document.Map.Monsters.Count == 1, "redo monster deletion");
        selectedId = id;
        document.PlaceNpc(null, new(-1.25f, 0, -1));
        ClickHeader("Save"); string saved = document.Map.Serialize();
        Verify(!document.Dirty && MapData.Load(mapPath).Serialize() == saved, "save/load includes monsters and stats");
        document.Map.Save(Path.Combine(ProjectPaths.Root, "Editor", "obj", "monster-runtime-test.json"));
        Press(KeyboardKey.F5); var session = play!; var enemy = session.Map.Monsters.Single(); float spawnX = enemy.X;
        for (int i = 0; i < 12; i++) TestFrame();
        Verify(enemy.X < spawnX && session.Monsters.Single().Mode == MonsterMode.Chasing, "playtest monster chases the player");
        Press(KeyboardKey.I); var pausedPosition = enemy.Position; int hp = session.PlayerHealth;
        Input(2, (int)KeyboardKey.Space); for (int i = 0; i < 12; i++) TestFrame(); Input(1, (int)KeyboardKey.Space); TestFrame();
        Verify(session.InventoryOpen && enemy.Position == pausedPosition && session.PlayerHealth == hp && session.Monsters.Single().Health == 35, "open inventory pauses movement and combat input");
        Press(KeyboardKey.Escape); Press(KeyboardKey.E); pausedPosition = enemy.Position;
        for (int i = 0; i < 12; i++) TestFrame();
        Verify(session.Dialogue.Active && enemy.Position == pausedPosition, "dialogue pauses monster movement");
        Press(KeyboardKey.Escape);
        for (int i = 0; i < 140 && session.PlayerHealth == 100; i++) TestFrame();
        Verify(session.PlayerHealth == 89, "monster attacks using its edited damage");
        TestFrame(); TestFrame(); WorldRenderer.Screenshot(Path.Combine(ProjectPaths.Root, "Editor", "obj", "monster-playtest.png"));
        Input(2, (int)KeyboardKey.Space);
        for (int i = 0; i < 120 && session.Map.Monsters.Count > 0; i++) TestFrame();
        Input(1, (int)KeyboardKey.Space); TestFrame();
        Verify(session.PlayerAlive && session.Map.Monsters.Count == 0, "holding Space kills a nearby monster");
        Press(KeyboardKey.F5);
        Verify(play == null && document.Map.Serialize() == saved && !document.Dirty, "playtest combat preserves the saved editor map");

        document.Checkpoint(); monster = document.Map.Monsters.Single(); monster.X = 4; monster.Z = 0; monster.Damage = 100; monster.MoveSpeed = 10;
        string lethal = document.Map.Serialize(); Press(KeyboardKey.F5); session = play!;
        for (int i = 0; i < 120 && session.PlayerAlive; i++) TestFrame();
        Verify(!session.PlayerAlive, "monster can defeat the player");
        var deathPosition = session.Player; Input(2, (int)KeyboardKey.D); for (int i = 0; i < 4; i++) TestFrame(); Input(1, (int)KeyboardKey.D); TestFrame();
        Verify(session.Player == deathPosition, "defeated player cannot move");
        TestFrame(); TestFrame(); WorldRenderer.Screenshot(Path.Combine(ProjectPaths.Root, "Editor", "obj", "monster-death.png"));
        Press(KeyboardKey.Enter); Verify(session.PlayerHealth == 100 && session.Monsters.Single().Health == 35 && session.Player == Vector3.Zero, "Enter restarts combat and restores the spawn");
        Press(KeyboardKey.F5); Verify(document.Map.Serialize() == lethal, "death and restart also preserve the editor map");
        ClickHeader("Undo"); Verify(document.Map.Serialize() == saved && !document.Dirty, "test fixture changes can be undone");
        selectedId = id; TestFrame(); TestFrame();
        Console.WriteLine("Monster interaction checks passed: toolbar/keyboard, placement, picking/dragging, name/sprite/stats, undo/redo, duplication/deletion, save/load, minimum window, chase/attacks, panel pause, Space, death/Enter and playtest isolation.");
    }
}
